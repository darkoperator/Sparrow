/// Name of an AuditLogRecordType number.
pub fn record_type_name(value: i16) -> Option<&'static str> {
    RECORD_TYPES
        .binary_search_by_key(&value, |(v, _)| *v)
        .ok()
        .map(|i| RECORD_TYPES[i].1)
}

/// Number of an AuditLogRecordType name (case-insensitive).
pub fn record_type_value(name: &str) -> Option<i16> {
    RECORD_TYPES
        .iter()
        .find(|(_, n)| n.eq_ignore_ascii_case(name))
        .map(|(v, _)| *v)
}
